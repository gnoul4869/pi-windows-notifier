import assert from "node:assert/strict";
import { test } from "node:test";
import { defaults } from "../src/config.ts";
import { NotificationScheduler, QUEUE_TTL } from "../src/scheduler.ts";
import type { Backend, LaunchResult } from "../src/launcher.ts";
import type { NotificationJob, NotificationPayload } from "../src/types.ts";
import { FakeClock, flush } from "./clock.ts";

const ok: LaunchResult = { code: "OK", toast: true, sound: "played" };
function fixture() {
  const clock = new FakeClock();
  const config = defaults();
  const calls: Array<{ kind: string; payload: NotificationPayload; signal: AbortSignal; resolve(result: LaunchResult): void }> = [];
  const diagnostics: string[] = [];
  const backend: Backend = { available: true, code: "OK", launch: (payload, signal) =>
    new Promise(resolve => { calls.push({ kind: payload.kind, payload, signal, resolve });
      signal.addEventListener("abort", () => resolve({ code: "CANCELLED", toast: false, sound: "failed" }), { once: true });
    }) };
  const scheduler = new NotificationScheduler(backend, () => config, code => diagnostics.push(code), clock);
  const job = (key: string, kind: NotificationJob["kind"] = "question", valid = () => true): NotificationJob => ({ key, kind, valid });
  return { clock, config, calls, diagnostics, scheduler, job };
}
test("Waiting events go first, at least one second apart, at most one helper", async () => {
  const { clock, calls, scheduler, job } = fixture();
  const completed = scheduler.submit(job("run", "completed"));
  const question = scheduler.submit(job("q"));
  clock.advance(0);
  assert.equal(calls[0].kind, "question");
  clock.advance(300);
  assert.equal(calls.length, 1);
  calls[0].resolve(ok);
  assert.equal((await question).status, "submitted");
  await flush();
  clock.advance(699);
  assert.equal(calls.length, 1);
  clock.advance(1);
  assert.equal(calls[1].kind, "completed");
  calls[1].resolve(ok);
  await completed;
  await scheduler.close();
});
test("The queue is bounded under a flood of events, dropping completed items first", async () => {
  const { scheduler, clock, calls, job, diagnostics } = fixture();
  const completed = scheduler.submit(job("old", "completed"));
  for (let i = 0; i < 16; i++) scheduler.enqueue(job(String(i)));
  assert.equal((await completed).status, "dropped");
  assert.equal(scheduler.status().queued, 16);
  assert.equal(scheduler.dropped, 1);
  scheduler.enqueue(job("extra"));
  assert.equal(scheduler.dropped, 2);
  assert.ok(diagnostics.includes("QUEUE_DROPPED"));
  clock.advance(0);
  assert.equal(calls.length, 1);
  await scheduler.close();
  assert.equal(clock.count(), 0);
});
test("Cancellation, TTL, validity re-check, and disabled re-check", async () => {
  const { scheduler, clock, calls, job, config, diagnostics } = fixture();
  const cancelled = scheduler.submit(job("cancel"));
  scheduler.cancel("cancel");
  assert.equal((await cancelled).status, "cancelled");
  const active = scheduler.submit(job("active"));
  const stale = scheduler.submit(job("stale"));
  clock.advance(0);
  clock.advance(QUEUE_TTL);
  calls[0].resolve(ok);
  await active;
  await flush();
  clock.advance(0);
  assert.equal((await stale).status, "expired");
  assert.ok(diagnostics.includes("DROP_EXPIRED"));
  let valid = true;
  const invalid = scheduler.submit(job("invalid", "question", () => valid));
  valid = false;
  clock.advance(1_000);
  assert.equal((await invalid).status, "cancelled");
  const disabled = scheduler.submit(job("disabled"));
  config.enabled = false;
  clock.advance(1_000);
  assert.equal((await disabled).status, "disabled");
  assert.equal((await scheduler.submit(job("off"))).status, "disabled");
  await scheduler.close();
});
test("Per-event switches and mute, duplicate keys, and a close that is repeatable and ends only its own work", async () => {
  const { scheduler, clock, config, calls, job } = fixture();
  config.events.permission.enabled = false;
  assert.equal((await scheduler.submit(job("p", "permission"))).status, "disabled");
  config.events.question.sound.enabled = false;
  const pending = scheduler.submit(job("q"));
  assert.equal((await scheduler.submit(job("q"))).status, "cancelled");
  clock.advance(0);
  assert.equal(calls[0].payload.sound.enabled, false);
  const queued = scheduler.submit(job("queued"));
  await scheduler.close();
  await scheduler.close();
  assert.equal(calls[0].signal.aborted, true);
  assert.equal((await pending).status, "cancelled");
  assert.equal((await queued).status, "cancelled");
  assert.equal(clock.count(), 0);
});
test("Independent channels, both disabled, config re-read after queuing, and payload snapshots", async () => {
  const { scheduler, clock, config, calls, job } = fixture();
  config.events.question.toast.enabled = false;
  config.events.question.sound.enabled = false;
  assert.equal((await scheduler.submit(job("none"))).status, "disabled");
  assert.equal(clock.count(), 0);
  config.events.question.sound.enabled = true;
  config.events.question.sound.volume = 0.2;
  const soundOnly = scheduler.submit(job("sound"));
  config.events.question.toast.title = "Custom";
  config.events.question.sound.source = { type: "system", name: "Hand" };
  clock.advance(0);
  assert.equal(calls[0].payload.toast.enabled, false);
  assert.equal(calls[0].payload.toast.title, "Custom");
  assert.deepEqual(calls[0].payload.sound.source, { type: "system", name: "Hand" });
  assert.equal(calls[0].payload.sound.volume, 0.2);
  assert.ok(config.events.question.sound.source.type === "system");
  config.events.question.sound.source.name = "Beep";
  assert.deepEqual(calls[0].payload.sound.source, { type: "system", name: "Hand" });
  config.events.question.sound.volume = 0.9;
  assert.equal(calls[0].payload.sound.volume, 0.2);
  calls[0].resolve({ code: "OK", toast: false, sound: "played" });
  assert.equal((await soundOnly).status, "submitted");
  await flush();
  config.events.question.toast.enabled = true;
  config.events.question.sound.enabled = false;
  const toastOnly = scheduler.submit(job("toast"));
  clock.advance(1_000);
  assert.equal(calls[1].payload.sound.enabled, false);
  calls[1].resolve({ code: "OK", toast: true, sound: "disabled" });
  assert.equal((await toastOnly).status, "submitted");
  await scheduler.close();
});
test("Disabling both channels after queuing cancels the submission and starts no helper", async () => {
  const { scheduler, clock, config, calls, job } = fixture();
  const pending = scheduler.submit(job("off"));
  config.events.question.toast.enabled = false;
  config.events.question.sound.enabled = false;
  clock.advance(0);
  assert.equal((await pending).status, "disabled");
  assert.equal(calls.length, 0);
  await scheduler.close();
});
test("Partial success and launcher failure throw nothing and never retry automatically", async () => {
  const { scheduler, clock, calls, job } = fixture();
  const partial = scheduler.submit(job("partial"));
  clock.advance(0);
  calls[0].resolve({ code: "TOAST_FAILED", toast: false, sound: "played" });
  assert.equal((await partial).status, "partial");
  await flush();
  clock.advance(60_000);
  assert.equal(calls.length, 1);
  await scheduler.close();
  const broken = new NotificationScheduler({ available: true, code: "OK", launch: async () => { throw new Error("SECRET"); } },
    defaults, () => {}, clock);
  const failed = broken.submit(job("failed"));
  clock.advance(0);
  assert.deepEqual(await failed, { status: "failed", code: "LAUNCH_FAILED" });
  await broken.close();
});
test("Every drop reason carries a diagnosable code", async () => {
  const disabled = fixture();
  disabled.config.enabled = false;
  assert.equal((await disabled.scheduler.submit(disabled.job("off"))).status, "disabled");
  assert.ok(disabled.diagnostics.includes("DROP_DISABLED"));
  await disabled.scheduler.close();

  const stale = fixture();
  let valid = true;
  const staleResult = stale.scheduler.submit(stale.job("stale", "question", () => valid));
  valid = false;
  stale.clock.advance(1_000);
  assert.equal((await staleResult).status, "cancelled");
  assert.ok(stale.diagnostics.includes("DROP_STALE"));
  await stale.scheduler.close();

  const duplicate = fixture();
  const first = duplicate.scheduler.submit(duplicate.job("dup"));
  assert.equal((await duplicate.scheduler.submit(duplicate.job("dup"))).status, "cancelled");
  assert.ok(duplicate.diagnostics.includes("DROP_DUPLICATE"));
  duplicate.clock.advance(0);
  duplicate.calls[0].resolve(ok);
  await first;
  await duplicate.scheduler.close();

  const cancelled = fixture();
  const queued = cancelled.scheduler.submit(cancelled.job("queued"));
  cancelled.scheduler.cancel("queued");
  assert.equal((await queued).status, "cancelled");
  assert.ok(cancelled.diagnostics.includes("DROP_CANCELLED"));

  const aborted = fixture();
  const running = aborted.scheduler.submit(aborted.job("run", "completed"));
  aborted.clock.advance(0);
  aborted.scheduler.cancel("run");
  assert.ok(aborted.diagnostics.includes("DROP_ABORTED"));
  assert.equal((await running).status, "cancelled");
  await aborted.scheduler.close();

  const shutdown = fixture();
  const pending = shutdown.scheduler.submit(shutdown.job("pending"));
  const active = shutdown.scheduler.submit(shutdown.job("active"));
  shutdown.clock.advance(0);
  await shutdown.scheduler.close();
  assert.equal((await pending).status, "cancelled");
  assert.equal((await active).status, "cancelled");
  assert.ok(shutdown.diagnostics.includes("DROP_SHUTDOWN"));
});
